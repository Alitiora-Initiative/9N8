create table if not exists public.n8_paper_positions (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.n8_paper_sessions(id) on delete cascade,
  user_id uuid not null references public.n8_users(id) on delete cascade,
  instrument_id uuid not null references public.n8_market_instruments(id) on delete restrict,
  symbol text not null,
  quantity numeric(28,12) not null default 0 check (quantity >= 0),
  average_entry_price numeric(28,12) not null check (average_entry_price > 0),
  mark_price numeric(28,12),
  entry_fees_usd numeric(20,8) not null default 0 check (entry_fees_usd >= 0),
  realized_pnl_usd numeric(20,8) not null default 0,
  unrealized_pnl_usd numeric(20,8) not null default 0,
  stop_loss_price numeric(28,12) not null,
  take_profit_price numeric(28,12) not null,
  status text not null default 'open' check (status in ('open','closed')),
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (session_id, instrument_id)
);

create table if not exists public.n8_paper_trades (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.n8_paper_sessions(id) on delete cascade,
  user_id uuid not null references public.n8_users(id) on delete cascade,
  instrument_id uuid not null references public.n8_market_instruments(id) on delete restrict,
  symbol text not null,
  side text not null check (side in ('buy','sell')),
  quantity numeric(28,12) not null check (quantity > 0),
  fill_price numeric(28,12) not null check (fill_price > 0),
  reference_price numeric(28,12) not null check (reference_price > 0),
  notional_usd numeric(20,8) not null check (notional_usd > 0),
  fee_usd numeric(20,8) not null default 0 check (fee_usd >= 0),
  realized_pnl_usd numeric(20,8),
  idempotency_key text not null,
  signal_reason text not null,
  candle_open_time timestamptz not null,
  filled_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique (session_id, idempotency_key)
);

