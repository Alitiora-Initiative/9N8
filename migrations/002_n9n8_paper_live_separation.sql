-- 9N8 paper/live separation. Paper records never share the live positions or receipt ledger.
BEGIN;

ALTER TABLE public.n9n8_positions
    ADD COLUMN IF NOT EXISTS peak_value_lamports NUMERIC(30,0) NOT NULL DEFAULT 0;
ALTER TABLE public.n9n8_positions
    ADD COLUMN IF NOT EXISTS tp1_done BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.n9n8_positions
    ADD COLUMN IF NOT EXISTS tp2_done BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS public.n9n8_paper_settings (
    telegram_id BIGINT PRIMARY KEY REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    config_json JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.n9n8_paper_accounts (
    telegram_id BIGINT PRIMARY KEY REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    starting_balance_lamports NUMERIC(30,0) NOT NULL CHECK (starting_balance_lamports > 0),
    cash_balance_lamports NUMERIC(30,0) NOT NULL CHECK (cash_balance_lamports >= 0),
    realized_pnl_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.n9n8_paper_days (
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    day_utc DATE NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (telegram_id, day_utc)
);

CREATE TABLE IF NOT EXISTS public.n9n8_paper_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    mint TEXT NOT NULL,
    launchpad TEXT NOT NULL,
    token_amount_raw NUMERIC(30,0) NOT NULL CHECK (token_amount_raw >= 0),
    initial_cost_lamports NUMERIC(30,0) NOT NULL CHECK (initial_cost_lamports >= 0),
    entry_price_usd NUMERIC(38,18) NOT NULL DEFAULT 0,
    status TEXT NOT NULL CHECK (status IN ('open','closed')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    exit_reason TEXT,
    realized_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    peak_value_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    last_value_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    last_pnl_pct NUMERIC(18,6) NOT NULL DEFAULT 0,
    tp1_done BOOLEAN NOT NULL DEFAULT FALSE,
    tp2_done BOOLEAN NOT NULL DEFAULT FALSE,
    buy_reference TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS n9n8_paper_positions_user_status_idx
    ON public.n9n8_paper_positions(telegram_id, status, id);
CREATE UNIQUE INDEX IF NOT EXISTS n9n8_paper_positions_one_open_mint_idx
    ON public.n9n8_paper_positions(telegram_id, mint) WHERE status='open';

CREATE TABLE IF NOT EXISTS public.n9n8_paper_trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    position_id BIGINT REFERENCES public.n9n8_paper_positions(id) ON DELETE SET NULL,
    side TEXT NOT NULL CHECK (side IN ('buy','sell','rejected')),
    mint TEXT NOT NULL,
    launchpad TEXT,
    token_amount_raw NUMERIC(30,0) NOT NULL DEFAULT 0,
    sol_amount_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    fee_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    price_usd NUMERIC(38,18) NOT NULL DEFAULT 0,
    reason TEXT,
    reference_signature TEXT,
    quote_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS n9n8_paper_trades_user_time_idx
    ON public.n9n8_paper_trades(telegram_id, created_at DESC);
CREATE INDEX IF NOT EXISTS n9n8_paper_trades_position_idx
    ON public.n9n8_paper_trades(position_id, created_at);

-- Default practice settings are isolated from the live strategy settings.
INSERT INTO public.n9n8_paper_settings(telegram_id, config_json)
SELECT telegram_id,
       jsonb_build_object(
         'launchpad', 'both',
         'buy_amount_sol', '0.05',
         'slippage_pct', '15',
         'priority_fee_lamports', 10000,
         'jito_tip_lamports', 2000000,
         'take_profit_pct', '100',
         'take_profit_2_pct', '300',
         'take_profit_2_sell_pct', '25',
         'trailing_stop_pct', '20',
         'stop_loss_pct', '30',
         'max_hold_seconds', 14400,
         'moon_bag_pct', '50',
         'daily_position_limit', 5,
         'max_daily_drawdown_pct', '15',
         'mev_shield', true,
         'min_liquidity_sol', '5',
         'min_lp_locked_pct', '80',
         'min_liquidity_usd', '0',
         'pump_mode', 'migration',
         'pump_migration_progress_pct', '80',
         'max_top10_concentration_pct', '25',
         'max_dev_wallet_pct', '5',
         'require_mint_authority_revoked', true,
         'require_freeze_authority_revoked', true
       )
FROM public.n9n8_users
ON CONFLICT (telegram_id) DO NOTHING;

-- Live-mode user consent is an independent switch. Existing legacy enabled accounts
-- are deliberately NOT automatically armed for live trading.
UPDATE public.n9n8_settings
SET config_json = jsonb_set(
    jsonb_set(config_json, '{live_enabled}', 'false'::jsonb, true),
    '{paper_enabled}', 'false'::jsonb, true
)
WHERE NOT (config_json ? 'live_enabled')
   OR NOT (config_json ? 'paper_enabled');

COMMIT;
