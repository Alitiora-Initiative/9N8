-- 9N8 dedicated PostgreSQL schema. This migration is isolated from vyra-markets.
CREATE TABLE IF NOT EXISTS public.n9n8_users (
    telegram_id BIGINT PRIMARY KEY,
    activation_paid BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.n9n8_wallet_vault (
    telegram_id BIGINT PRIMARY KEY REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    solana_address TEXT NOT NULL UNIQUE,
    encrypted_secret BYTEA NOT NULL,
    payout_address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.n9n8_settings (
    telegram_id BIGINT PRIMARY KEY REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    config_json JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.n9n8_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE RESTRICT,
    mint TEXT NOT NULL,
    token_amount_raw NUMERIC(30,0) NOT NULL,
    initial_cost_lamports NUMERIC(30,0) NOT NULL,
    entry_price_usd NUMERIC(38,18) NOT NULL DEFAULT 0,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL CHECK (status IN ('open','closed')),
    moon_bag_raw NUMERIC(30,0) NOT NULL DEFAULT 0,
    exit_reason TEXT,
    realized_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    buy_signature TEXT,
    sell_signature TEXT
);
CREATE INDEX IF NOT EXISTS n9n8_positions_user_status_idx
    ON public.n9n8_positions(telegram_id, status, id);
CREATE UNIQUE INDEX IF NOT EXISTS n9n8_positions_one_open_mint_idx
    ON public.n9n8_positions(telegram_id, mint) WHERE status = 'open';
CREATE TABLE IF NOT EXISTS public.n9n8_fee_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE RESTRICT,
    fee_type TEXT NOT NULL,
    amount_lamports NUMERIC(30,0) NOT NULL CHECK (amount_lamports > 0),
    tx_signature TEXT NOT NULL,
    idempotency_key TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS n9n8_fee_ledger_user_type_idx
    ON public.n9n8_fee_ledger(telegram_id, fee_type, created_at DESC);
CREATE TABLE IF NOT EXISTS public.n9n8_daily_risk (
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE RESTRICT,
    day_utc DATE NOT NULL,
    starting_equity_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    realized_pnl_lamports NUMERIC(30,0) NOT NULL DEFAULT 0,
    trade_count INTEGER NOT NULL DEFAULT 0 CHECK (trade_count >= 0),
    PRIMARY KEY (telegram_id, day_utc)
);
CREATE TABLE IF NOT EXISTS public.n9n8_security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT REFERENCES public.n9n8_users(telegram_id) ON DELETE SET NULL,
    event_type TEXT NOT NULL,
    detail TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS n9n8_security_events_user_time_idx
    ON public.n9n8_security_events(telegram_id, created_at DESC);
CREATE TABLE IF NOT EXISTS public.n9n8_trade_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE RESTRICT,
    position_id BIGINT REFERENCES public.n9n8_positions(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL CHECK (event_type IN ('buy','sell','fee','withdrawal','wallet_rotation','deposit')),
    mint TEXT,
    signature TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('submitted','confirmed','finalized','failed','unknown')),
    amount_lamports NUMERIC(30,0),
    token_amount_raw NUMERIC(30,0),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    confirmed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS n9n8_trade_receipts_user_time_idx
    ON public.n9n8_trade_receipts(telegram_id, created_at DESC);
CREATE TABLE IF NOT EXISTS public.n9n8_worker_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE RESTRICT,
    job_type TEXT NOT NULL CHECK (job_type IN ('panic_sell','withdraw_all','rotate_wallet')),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','running','succeeded','failed','unknown')),
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 1,
    idempotency_key TEXT NOT NULL UNIQUE,
    result_json JSONB,
    last_error TEXT,
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at TIMESTAMPTZ,
    locked_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS n9n8_worker_jobs_claim_idx
    ON public.n9n8_worker_jobs(status, available_at, id);
CREATE INDEX IF NOT EXISTS n9n8_worker_jobs_user_idx
    ON public.n9n8_worker_jobs(telegram_id, created_at DESC);
CREATE TABLE IF NOT EXISTS public.n9n8_worker_heartbeats (
    worker_id TEXT PRIMARY KEY,
    status TEXT NOT NULL,
    trading_mode TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS public.n9n8_telemetry_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL REFERENCES public.n9n8_users(telegram_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    event_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS n9n8_telemetry_user_id_idx
    ON public.n9n8_telemetry_events(telegram_id, id);
CREATE TABLE IF NOT EXISTS public.n9n8_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT REFERENCES public.n9n8_users(telegram_id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS n9n8_audit_events_user_time_idx
    ON public.n9n8_audit_events(telegram_id, created_at DESC);